import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import sharp from 'sharp';
import { createApp } from '../backend/src/server.mjs';

const {server,store}=await createApp({file:':memory:',demo:true});
server.listen(0,'127.0.0.1');await once(server,'listening');
const base='http://127.0.0.1:'+server.address().port;
const out='.runtime/qa';
let browser;
try {
  await mkdir(out,{recursive:true});
  browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1024},acceptDownloads:true});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('button',{name:'Sơ mi linen Mộc',exact:true}).waitFor();
  await page.screenshot({path:out+'/shop-desktop.png'});
  const images=await page.locator('.product-media img').evaluateAll(imgs=>imgs.slice(0,4).every(i=>i.complete&&i.naturalWidth>0));
  assert.ok(images);
  await page.getByLabel('Tìm sản phẩm').fill('áo sơ mi đi làm cho da ngăm dưới 500k');
  await page.getByLabel('Tìm sản phẩm').press('Enter');
  await page.getByText('1 sản phẩm',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Mở AI Stylist'}).click();
  await page.getByRole('button',{name:'Phối đồ đi chơi cuối tuần'}).click();
  const recommendation=page.getByRole('link',{name:'Thử ngay'}).first();
  await recommendation.waitFor();
  const target=await recommendation.getAttribute('href');
  await recommendation.click();
  assert.ok(page.url().endsWith(target));
  await page.getByAltText(/^Kết quả thử/).waitFor();
  await page.screenshot({path:out+'/fitting-desktop.png'});
  const frame=await page.getByTestId('model-frame').boundingBox();
  assert.ok(Math.abs(frame.width/frame.height-.75)<.005);
  await page.getByRole('slider',{name:'Chiều cao'}).press('ArrowRight');
  await page.getByText('Cập nhật vóc dáng để thử với số đo mới.').waitFor();
  await page.getByRole('button',{name:'Cập nhật vóc dáng'}).click();
  await page.getByAltText(/^Kết quả thử/).waitFor();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Tải phôi PNG 768 × 1024'}).click()]);
  const {width,height}=await sharp(await download.path()).metadata();
  assert.deepEqual([width,height],[768,1024]);
  await page.getByRole('button',{name:'Lưu lượt thử',exact:true}).click();
  await page.getByRole('button',{name:'Đã lưu lượt thử',exact:true}).waitFor();
  await page.getByRole('button',{name:'Thêm vào giỏ',exact:true}).click();
  let dialog=page.getByRole('dialog');
  const sizes=dialog.locator('.size-options button:not([disabled])');
  await sizes.first().click();
  await dialog.getByRole('button',{name:'Thêm vào giỏ'}).click();
  await page.getByRole('button',{name:'Giỏ hàng (1)',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Tăng số lượng'}).click();
  await dialog.getByRole('heading',{name:'Giỏ hàng (2)'}).waitFor();
  await dialog.getByRole('button',{name:'Đóng',exact:true}).click();
  await page.getByRole('link',{name:'Tài khoản',exact:true}).click();
  await page.getByRole('button',{name:'Vào bằng tài khoản quản trị demo'}).click();
  await page.getByRole('heading',{name:'Quản trị demo'}).waitFor();
  await page.locator('.history-item').first().waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Giỏ hàng (2)',exact:true}).waitFor();
  await page.locator('.history-item').first().click();
  await page.getByAltText(/^Kết quả thử/).waitFor();
  await page.getByRole('button',{name:'Mở AI Stylist'}).click();
  await page.getByRole('log').getByText('Phối đồ đi chơi cuối tuần').waitFor();
  await page.screenshot({path:out+'/chat-desktop.png'});
  assert.deepEqual(errors,[]);
  for (const width of [390, 768]) {
    const mobile=await browser.newPage({viewport:{width,height:844},isMobile:width===390,deviceScaleFactor:1,hasTouch:true});
    mobile.on('pageerror',e=>errors.push(e.message));
    await mobile.goto(base);
    await mobile.getByRole('button',{name:'Sơ mi linen Mộc',exact:true}).waitFor();
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    if(width===390)await mobile.screenshot({path:out+'/shop-mobile.png'});
    await mobile.getByRole('link',{name:'Thử đồ',exact:true}).first().click();
    await mobile.getByAltText(/^Kết quả thử/).waitFor();
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    if(width===390)await mobile.screenshot({path:out+'/fitting-mobile.png'});
    await mobile.getByRole('button',{name:'Mở AI Stylist'}).click();
    assert.ok(await mobile.getByRole('log').isVisible());
    assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await mobile.close();
  }
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: shop → search → chat → fitting → PNG → cart → admin → saved history, at desktop/tablet/mobile sizes.');
} finally {
  await browser?.close();
  await new Promise(resolve=>server.close(resolve));
  store.db.close();
}
